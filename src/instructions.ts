import type { Context } from "./context.ts";
import { globMatches } from "./files.ts";

const code = (values: readonly string[]): string =>
  values.map((value) => `\`${value}\``).join(", ");

// what the policy asks of one file, for an agent to read before it edits that file
export function fileConventions(
  ctx: Pick<Context, "config" | "writableFiles">,
  path: string,
): Record<string, unknown> {
  const { config } = ctx,
    matching = <T extends { files: readonly string[] }>(entries: readonly T[] | undefined): T[] =>
      (entries ?? []).filter((entry) => globMatches(entry.files, path));
  return {
    // a protected file is never written by fix or sync, and its change needs an owner's review
    writable: ctx.writableFiles.includes(path),
    names: matching(config.files?.names).map(({ pattern, reason }) => ({ pattern, reason })),
    ...(config.files?.maxLines ? { maxLines: config.files.maxLines } : {}),
    rules: matching(config.rules).map((rule) => ({ ...rule, id: `custom.${rule.id}` })),
    boundaries: (config.contracts?.boundaries ?? [])
      .filter((entry) => globMatches(entry.from, path))
      .map(({ deny, reason }) => ({ deny, reason })),
    roles: matching(config.conventions?.roles).map((role) => role.id),
    exceptions: matching(config.exceptions).map(({ id, rules, max }) => ({ id, rules, max })),
  };
}

// the effective policy as instructions an agent can follow, generated so it never drifts from
// what the check enforces
export function instructions(ctx: Pick<Context, "config" | "configFile">): string {
  const { config } = ctx,
    out: string[] = [
      "# Repository conventions",
      "",
      `Generated by \`plumb instructions\` from the effective policy (\`${ctx.configFile}\`, preset \`${config.preset}\`). Change the policy, not this text.`,
      "",
      "## Workflow",
      "",
      "- Before editing a file, run `plumb inspect --file PATH` and follow the conventions it lists.",
      "- After editing, run `plumb check`. Exit 0 is the only pass; exit 2 means a check could not run, which is a failure to fix and never a result to work around.",
      "- `plumb fix` repairs formatting and generated regions. `plumb explain RULE` gives a rule's purpose and remedy.",
      "- Never edit the policy, an exception, an API snapshot or a protected file to make a check pass; those change only by review.",
    ];
  const section = (title: string, lines: readonly string[]): void => {
    if (lines.length) {
      out.push("", `## ${title}`, "", ...lines.map((line) => `- ${line}`));
    }
  };
  section(
    "Projects",
    config.projects.map((project) => `\`${project.root}\` is a ${project.profile} project.`),
  );
  section("Files", [
    ...(config.files?.required?.length ? [`Required: ${code(config.files.required)}.`] : []),
    ...(config.files?.forbidden?.length
      ? [`Never add files matching ${code(config.files.forbidden)}.`]
      : []),
    ...(config.files?.names ?? []).map(
      (entry) => `${code(entry.files)} are named \`${entry.pattern}\`: ${entry.reason}`,
    ),
    ...(config.files?.maxLines ? [`A file has at most ${config.files.maxLines} lines.`] : []),
  ]);
  section(
    "Protected files",
    config.policy?.protected?.length
      ? [`Change ${code(config.policy.protected)} only with an owner's review.`]
      : [],
  );
  section(
    "Rules",
    (config.rules ?? []).map(
      (rule) =>
        `\`custom.${rule.id}\` (${code(rule.files)}): ${rule.reason}${rule.remedy ? ` ${rule.remedy}` : ""}`,
    ),
  );
  section(
    "Boundaries",
    (config.contracts?.boundaries ?? []).map(
      (entry) => `${code(entry.from)} never import ${code(entry.deny)}: ${entry.reason}`,
    ),
  );
  section(
    "Roles",
    (config.conventions?.roles ?? []).map(
      (role) =>
        `\`${role.id}\`: ${code(role.files)}${role.name ? `, named \`${role.name}\`` : ""}. Create one with \`plumb scaffold ${role.id} NAME\`.`,
    ),
  );
  section(
    "Commits",
    config.commits
      ? [
          "One title-only Conventional Commit per change: `type(scope): subject`, lowercase subject, no trailing period.",
          ...(config.commits.types ? [`Types: ${code(config.commits.types)}.`] : []),
          ...(config.commits.scopes ? [`Scopes: ${code(config.commits.scopes)}.`] : []),
          ...(config.commits.maxLength ? [`At most ${config.commits.maxLength} characters.`] : []),
        ]
      : [],
  );
  section(
    "Tests",
    (config.verification ?? []).map(
      (suite) =>
        `Suite \`${suite.id}\` must pass${suite.coverage ? ` with at least ${suite.coverage.minLines}% line coverage` : ""}; it runs as part of \`plumb check\`.`,
    ),
  );
  section(
    "Exceptions",
    config.exceptions.length
      ? [
          `${config.exceptions.length} budgeted exceptions exist for older code. Budgets only shrink: fix what you touch and never add or widen one.`,
        ]
      : [],
  );
  return `${out.join("\n")}\n`;
}
