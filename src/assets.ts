import type { Stats } from "node:fs";
import { chmodSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, posix } from "node:path";

import { workflowFiles } from "./ci.ts";
import type { Config } from "./config.ts";
import type { Diagnostic, Rule } from "./diagnostics.ts";
import { errorMessage } from "./errors.ts";
import { normalize, protectedPolicyFiles, safePath } from "./files.ts";
import { type GeneratedFile, hookFiles } from "./hooks.ts";

export interface Asset extends GeneratedFile {
  executable: boolean;
  declared?: boolean;
}

type AssetPolicy = Pick<
  Config,
  "preset" | "projects" | "format" | "generated" | "policy" | "hooks" | "commits" | "ci"
>;

interface AssetState {
  target: string;
  missing?: true;
  content?: string;
  matches?: boolean;
  mode?: boolean;
  owned?: boolean;
}

export const RULES: Rule[] = [
  {
    id: "generated.drift",
    description: "Generated assets match the effective policy byte for byte.",
    remedy: "Review the policy, then run plumb sync.",
    suppressible: false,
  },
  {
    id: "generated.mode",
    description: "Generated assets have the prescribed executable mode.",
    remedy: "Run plumb sync to restore the file mode.",
    suppressible: false,
  },
  {
    id: "generated.ownership",
    description: "Sync never adopts an unrelated file implicitly.",
    remedy: "Review and move the existing file aside before syncing.",
    suppressible: false,
  },
  {
    id: "generated.unsafe",
    description: "Generated files stay inside the repository without symlinks.",
    remedy: "Use a regular file without symlink parents.",
    suppressible: false,
  },
];

export const CLANG_FORMAT = Object.freeze({
  BasedOnStyle: "LLVM",
  ColumnLimit: 100,
  IndentWidth: 2,
  PointerAlignment: "Left",
  InsertBraces: true,
  InsertNewlineAtEOF: true,
  SortIncludes: "CaseSensitive",
  IncludeBlocks: "Regroup",
});

const HEADER = "# generated by @quayro/plumb; edit plumb.json, then run plumb sync";

// the one place a shipped asset is read; the standalone build embeds them by replacing this loader
export const asset = (name: string): string =>
  readFileSync(new URL(`./assets/${name}`, import.meta.url), "utf8");

const template = (name: string): string => `${HEADER}\n${asset(name)}`;

// files generated before the package rename carry an old scope and are still Plumb's to replace
const owned = (content: string): boolean =>
  content
    .split(/\r?\n/, 3)
    .some((line) => /^# generated by @(?:quayro|ozmikhail|ozlabs)\/plumb;/.test(line));

const diagnostic = (rule: string, path: string, message: string, remedy: string): Diagnostic => ({
  rule,
  path,
  message,
  remedy,
  suppressible: false,
});

const modeMatches = (stat: Stats, executable: boolean): boolean =>
  process.platform === "win32" || (stat.mode & 0o111) === (executable ? 0o111 : 0);

// CODEOWNERS is root-anchored like plumb globs; only a leading **/ floats, and dir/** becomes dir/.
const CODEOWNERS_HEADER = "# generated by plumb from policy.protected; edit plumb.json";

function codeowners(policy: NonNullable<Config["policy"]>): string {
  const owners = (policy.owners ?? []).join(" ");
  const anchored = (glob: string): string => {
    if (/[\s{}\\!#]/.test(glob)) {
      throw new Error(`${glob}: CODEOWNERS cannot express this protected glob`);
    }
    if (glob.endsWith("/**")) {
      return glob.startsWith("**/") ? glob.slice(0, -2) : `/${glob.slice(0, -2)}`;
    }
    return glob.startsWith("**/") ? glob : `/${glob}`;
  };
  const patterns = [
    "/plumb.json",
    ...[...protectedPolicyFiles, ...(policy.protected ?? [])].map(anchored),
  ];
  return `${CODEOWNERS_HEADER}\n${[...new Set(patterns)]
    .sort()
    .map((pattern) => `${pattern} ${owners}`)
    .join("\n")}\n`;
}

export function assetsFor(config: AssetPolicy): Asset[] {
  const files: (GeneratedFile & { declared?: boolean })[] = [];
  if (config.preset === "ozmikhail") {
    files.push({
      path: ".editorconfig",
      content: `${HEADER}\nroot = true\n\n[*]\ncharset = utf-8\nend_of_line = lf\nindent_style = space\nindent_size = 2\ninsert_final_newline = true\ntrim_trailing_whitespace = true\n`,
    });
  }
  files.push(...hookFiles(config, HEADER), ...workflowFiles(config, HEADER));
  if ((config.projects ?? []).some(({ profile }) => ["typescript", "react"].includes(profile))) {
    files.push({
      path: ".prettierignore",
      content: [
        HEADER,
        "**/.clang-format",
        "**/.clang-tidy",
        "**/.rubocop.yml",
        ...(config.format?.ignore ?? []).flatMap(({ path, reason }) => [
          `# ${reason.replaceAll(/\r?\n/g, " ")}`,
          path,
        ]),
        "",
      ].join("\n"),
    });
  }
  for (const project of config.projects ?? []) {
    const folder = project.root.replaceAll("\\", "/");
    const names =
      project.profile === "ruby"
        ? [[".rubocop.yml", "rubocop.yml"]]
        : project.profile === "cpp"
          ? [[".clang-tidy", "clang-tidy.yml"]]
          : [];
    if (project.profile === "cpp") {
      files.push({
        path: posix.join(folder, ".clang-format"),
        content: `${HEADER}\n${JSON.stringify(CLANG_FORMAT, null, 2)}\n`,
      });
      files.push({
        path: posix.join(folder, ".clang-format-ignore"),
        content: `${HEADER}\n# exclusions belong in the reviewed plumb.json policy\n`,
      });
    }
    for (const [name, source] of names) {
      files.push({ path: posix.join(folder, name), content: template(source) });
    }
  }
  if (config.policy?.owners?.length) {
    files.push({ path: ".github/CODEOWNERS", content: codeowners(config.policy), declared: true });
  }
  const result = new Map<string, Asset>();
  for (const file of files) {
    const prior = result.get(file.path);
    if (prior && prior.content !== file.content) {
      throw new Error(`${file.path}: generated assets disagree`);
    }
    result.set(file.path, { ...file, executable: file.executable ?? false });
  }
  for (const file of config.generated ?? []) {
    const path = normalize(file.path);
    if (result.has(path)) {
      throw new Error(
        `${path}: a project cannot replace a preset-owned or duplicate generated asset`,
      );
    }
    result.set(path, { ...file, path, executable: file.executable ?? false, declared: true });
  }
  for (const path of result.keys()) {
    for (
      let parent = posix.dirname(path);
      parent !== "." && parent !== "/";
      parent = posix.dirname(parent)
    ) {
      if (result.has(parent)) {
        throw new Error(`${parent}: a generated file cannot also be a directory for ${path}`);
      }
    }
  }
  return [...result.values()].sort((a, b) => a.path.localeCompare(b.path, "en"));
}

function inspect(root: string, asset: Asset): AssetState {
  const target = safePath(root, asset.path, { allowMissing: true });
  if (!existsSync(target)) {
    return { target, missing: true };
  }
  const stat = statSync(target);
  if (!stat.isFile()) {
    throw new Error(`${asset.path}: generated target is not a regular file`);
  }
  const content = readFileSync(target, "utf8");
  return {
    target,
    content,
    matches: content === asset.content,
    mode: modeMatches(stat, asset.executable),
    owned: owned(content),
  };
}

export function checkAssets({ root, config }: { root: string; config: AssetPolicy }): Diagnostic[] {
  const problems: Diagnostic[] = [];
  for (const asset of assetsFor(config)) {
    try {
      const state = inspect(root, asset);
      if (state.missing || !state.matches) {
        problems.push(
          diagnostic(
            "generated.drift",
            asset.path,
            state.missing
              ? "A generated asset is missing."
              : "A generated asset differs from the effective policy.",
            "Review the policy, then run plumb sync.",
          ),
        );
      }
      if (!state.missing && !state.mode) {
        problems.push(
          diagnostic(
            "generated.mode",
            asset.path,
            asset.executable
              ? "This generated file must be executable."
              : "This generated file must not be executable.",
            "Run plumb sync to restore the file mode.",
          ),
        );
      }
    } catch (error) {
      problems.push({
        ...diagnostic(
          "generated.unsafe",
          asset.path,
          errorMessage(error),
          "Use a regular file inside the repository, without symlink parents.",
        ),
        status: "incomplete",
      });
    }
  }
  return problems;
}

// explicit generated declarations confer ownership through reviewed policy, including JSON files.
// preset assets need their marker or exact bytes before sync may adopt an existing file.
export function syncAssets({ root, config }: { root: string; config: AssetPolicy }): {
  written: string[];
  diagnostics: Diagnostic[];
} {
  const plans: { asset: Asset; state: AssetState }[] = [];
  const diagnostics: Diagnostic[] = [];
  for (const asset of assetsFor(config)) {
    try {
      const state = inspect(root, asset);
      if (!state.missing && !state.matches && !state.owned && !asset.declared) {
        diagnostics.push(
          diagnostic(
            "generated.ownership",
            asset.path,
            "Refusing to replace an existing file that Plumb does not own.",
            "Review and move the file aside, then run plumb sync; keep needed settings in policy.",
          ),
        );
      } else {
        plans.push({ asset, state });
      }
    } catch (error) {
      diagnostics.push({
        ...diagnostic(
          "generated.unsafe",
          asset.path,
          errorMessage(error),
          "Use a regular file inside the repository, without symlink parents.",
        ),
        status: "incomplete",
      });
    }
  }
  if (diagnostics.length) {
    return { written: [], diagnostics };
  }
  const written: string[] = [];
  for (const { asset, state } of plans) {
    if (!state.missing && state.matches && state.mode) {
      continue;
    }
    mkdirSync(dirname(state.target), { recursive: true });
    safePath(root, asset.path, { allowMissing: true });
    if (state.missing || !state.matches) {
      writeFileSync(state.target, asset.content, { flag: state.missing ? "wx" : "w" });
    }
    if (process.platform !== "win32") {
      chmodSync(state.target, asset.executable ? 0o755 : 0o644);
    }
    written.push(asset.path);
  }
  return { written, diagnostics };
}
