import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  chmodSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test, { type TestContext } from "node:test";

import { assetsFor, checkAssets, syncAssets } from "../src/assets.ts";
import { main } from "../src/cli.ts";
import { definePlumb } from "../src/config.ts";
import { checkHookManager, checkHooks, hookFiles } from "../src/hooks.ts";
import { parseReport, testContext } from "./support.ts";

const command = ["bun", "--no-env-file", "tools/plumb/bin/plumb.mjs"];

const configure = (value: Record<string, unknown>): ReturnType<typeof definePlumb> =>
  definePlumb({ schemaVersion: 1, preset: "portable", ...value });

function fixture(t: TestContext) {
  const root = mkdtempSync(join(tmpdir(), "plumb-hooks-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  return root;
}

const git = (root: string, ...args: string[]): ReturnType<typeof spawnSync> =>
  spawnSync("git", args, { cwd: root, encoding: "utf8" });

await test("hook scripts run the configured argv with the check and commit-msg subcommands", () => {
  const files = assetsFor(configure({ hooks: { command }, commits: {} })).filter((file) =>
    file.path.startsWith(".githooks/"),
  );
  assert.deepEqual(
    files.map((file) => file.path),
    [".githooks/commit-msg", ".githooks/pre-commit"],
  );
  assert.ok(files.every((file) => file.executable === true));
  const [commitMsg, preCommit] = files;
  assert.match(preCommit.content, /^#!\/bin\/sh\n# generated by @quayro\/plumb;/);
  assert.match(
    preCommit.content,
    /set -eu\ncd "\$\(git rev-parse --show-toplevel\)"\nexec bun --no-env-file tools\/plumb\/bin\/plumb\.mjs check\n$/,
  );
  assert.match(
    commitMsg.content,
    /exec bun --no-env-file tools\/plumb\/bin\/plumb\.mjs commit-msg "\$1"\n$/,
  );
});

await test("commit-msg is generated only with commits and custom paths are normalized", () => {
  const onlyCheck = hookFiles(configure({ hooks: { command, path: "./.hooks/" } }), "# header");
  assert.deepEqual(
    onlyCheck.map((file) => file.path),
    [".hooks/pre-commit"],
  );
  assert.deepEqual(hookFiles(configure({ commits: {} }), "# header"), []);
  assert.deepEqual(
    assetsFor(configure({ commits: {} })).filter((file) => file.path.includes("hook")),
    [],
  );
});

await test("arguments with spaces and quotes are shell-quoted and stay one argv element", (t) => {
  const root = fixture(t),
    [preCommit] = hookFiles(
      { hooks: { command: ["node", "tools/my dir/plumb's.mjs", "a$b", ""] }, commits: {} },
      "# header",
    );
  assert.match(preCommit.content, /exec node 'tools\/my dir\/plumb'\\''s\.mjs' 'a\$b' '' check\n$/);
  mkdirSync(join(root, ".githooks"));
  writeFileSync(join(root, ".githooks/pre-commit"), preCommit.content);
  assert.equal(spawnSync("sh", ["-n", join(root, ".githooks/pre-commit")]).status, 0);
});

await test("sync writes executable hooks and check reports content and mode drift", (t) => {
  const root = fixture(t),
    config = configure({ hooks: { command }, commits: {} });
  assert.deepEqual(syncAssets({ root, config }).diagnostics, []);
  assert.deepEqual(checkAssets({ root, config }), []);
  if (process.platform !== "win32") {
    assert.equal(statSync(join(root, ".githooks/pre-commit")).mode & 0o111, 0o111);
  }
  writeFileSync(
    join(root, ".githooks/commit-msg"),
    "#!/bin/sh\n# generated by @ozmikhail/plumb; edited\nexit 0\n",
  );
  assert.deepEqual(
    checkAssets({ root, config }).map((item) => item.rule),
    ["generated.drift"],
  );
  syncAssets({ root, config });
  if (process.platform !== "win32") {
    chmodSync(join(root, ".githooks/pre-commit"), 0o644);
    assert.deepEqual(
      checkAssets({ root, config }).map((item) => item.rule),
      ["generated.mode"],
    );
  }
});

await test("sync refuses to adopt an unrelated hook file", (t) => {
  const root = fixture(t),
    config = configure({ hooks: { command } });
  mkdirSync(join(root, ".githooks"));
  writeFileSync(join(root, ".githooks/pre-commit"), "#!/bin/sh\necho mine\n");
  const result = syncAssets({ root, config });
  assert.equal(result.diagnostics[0].rule, "generated.ownership");
  assert.equal(readFileSync(join(root, ".githooks/pre-commit"), "utf8"), "#!/bin/sh\necho mine\n");
});

await test("doctor reports unset or wrong core.hooksPath and incomplete outside git", async (t) => {
  const root = fixture(t),
    config = configure({ hooks: { command } });
  assert.equal((await checkHooks(config, root))[0].rule, "hooks.git");
  assert.equal((await checkHooks(config, root))[0].status, "incomplete");
  assert.deepEqual(await checkHooks(configure({}), root), []);
  assert.equal(git(root, "init", "-q").status, 0);
  const unset = await checkHooks(config, root);
  assert.deepEqual(
    unset.map((item) => [item.rule, item.status, item.remedy]),
    [["hooks.unset", "violation", "git config core.hooksPath .githooks"]],
  );
  git(root, "config", "core.hooksPath", "hooks-elsewhere");
  assert.equal((await checkHooks(config, root))[0].rule, "hooks.unset");
  git(root, "config", "core.hooksPath", ".githooks/");
  assert.deepEqual(await checkHooks(config, root), []);
  const custom = configure({ hooks: { command, path: ".custom" } });
  assert.equal((await checkHooks(custom, root))[0].rule, "hooks.unset");
});

await test("the doctor command includes the hooks check", async (t) => {
  const root = fixture(t);
  git(root, "init", "-q");
  writeFileSync(
    join(root, "plumb.json"),
    JSON.stringify({ schemaVersion: 1, preset: "portable", hooks: { command } }),
  );
  let text = "";
  await main(["doctor", "--root", root, "--format", "json"], (chunk) => {
    text += chunk;
  });
  const output = parseReport(text);
  assert.ok(
    output.diagnostics.some(
      (item) =>
        item.rule === "hooks.unset" && item.remedy === "git config core.hooksPath .githooks",
    ),
  );
  assert.equal(
    output.diagnostics.some(
      (item) => item.rule === "generated.drift" && item.path === ".githooks/pre-commit",
    ),
    true,
  );
});

const PLUMB = "bun --no-env-file tools/plumb/bin/plumb.mjs";

function managed(t: TestContext, manager: string, files: Record<string, string>) {
  const root = fixture(t);
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(join(root, path, ".."), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  const config = configure({ hooks: { command, manager }, commits: {} });
  return checkHookManager(testContext({ root, config })).map((item) => [
    item.rule,
    item.path,
    item.status,
  ]);
}

await test("a hook manager keeps its own files and must run the exact policy invocation", (t) => {
  const config = configure({ hooks: { command, manager: "husky" }, commits: {} });
  // a manager owns its hook files, so nothing is generated for it
  assert.deepEqual(hookFiles(config, "# header"), []);
  assert.deepEqual(
    managed(t, "husky", {
      ".husky/pre-commit": `npx lint-staged\n${PLUMB} check\n`,
      ".husky/commit-msg": `exec ${PLUMB} commit-msg "$1"\n`,
    }),
    [],
  );
  assert.deepEqual(
    managed(t, "lefthook", {
      "lefthook.yml": `pre-commit:\n  commands:\n    plumb:\n      run: ${PLUMB} check\ncommit-msg:\n  commands:\n    plumb:\n      run: ${PLUMB} commit-msg {1}\n`,
    }),
    [],
  );
  assert.deepEqual(
    managed(t, "pre-commit", {
      ".pre-commit-config.yaml": `repos:\n  - repo: local\n    hooks:\n      - id: plumb\n        entry: "${PLUMB} check"\n      - id: plumb-message\n        entry: ${PLUMB} commit-msg\n`,
    }),
    [],
  );
});

await test("a weakened, commented or missing manager invocation never passes", (t) => {
  const message = `${PLUMB} commit-msg "$1"\n`;
  for (const line of [
    `# ${PLUMB} check`,
    `${PLUMB} check || true`,
    `${PLUMB} check --observe`,
    `${PLUMB} --observe check`,
    `echo ${PLUMB} check`,
    `${PLUMB} check; exit 0`,
    `${PLUMB} plan`,
    "",
  ]) {
    assert.deepEqual(
      managed(t, "husky", { ".husky/pre-commit": `${line}\n`, ".husky/commit-msg": message }),
      [["hooks.manager", ".husky/pre-commit", "violation"]],
      line,
    );
  }
  // the commit-msg hook is required once commits are policy; a file that is absent is incomplete
  assert.deepEqual(managed(t, "husky", { ".husky/pre-commit": `${PLUMB} check\n` }), [
    ["hooks.manager", "plumb.json", "incomplete"],
  ]);
  assert.deepEqual(managed(t, "lefthook", {}), [
    ["hooks.manager", "plumb.json", "incomplete"],
    ["hooks.manager", "plumb.json", "incomplete"],
  ]);
  assert.throws(
    () => configure({ hooks: { command, manager: "lefthook", path: ".hooks" } }),
    /hooks\.path/,
  );
});

await test("doctor accepts the manager's own install and reports a clone without it", async (t) => {
  const root = fixture(t);
  git(root, "init", "-q");
  const husky = configure({ hooks: { command, manager: "husky" } }),
    lefthook = configure({ hooks: { command, manager: "lefthook" } });
  assert.equal((await checkHooks(husky, root))[0]?.rule, "hooks.unset");
  for (const path of [".husky", ".husky/_"]) {
    git(root, "config", "core.hooksPath", path);
    assert.deepEqual(await checkHooks(husky, root), []);
  }
  git(root, "config", "--unset", "core.hooksPath");
  const missing = await checkHooks(lefthook, root);
  assert.deepEqual(
    missing.map((item) => [item.rule, item.remedy]),
    [["hooks.unset", "Run lefthook install in this clone."]],
  );
  writeFileSync(join(root, ".git/hooks/pre-commit"), "#!/bin/sh\n");
  assert.deepEqual(await checkHooks(lefthook, root), []);
});

await test("check reports a manager that does not run the policy", async (t) => {
  const root = fixture(t);
  writeFileSync(
    join(root, "plumb.json"),
    JSON.stringify({
      schemaVersion: 1,
      preset: "portable",
      hooks: { command: ["plumb"], manager: "pre-commit" },
    }),
  );
  writeFileSync(join(root, ".pre-commit-config.yaml"), "repos: []\n");
  let text = "";
  const code = await main(["check", "--root", root, "--format", "json"], (chunk) => {
    text += chunk;
  });
  assert.equal(code, 1);
  assert.deepEqual(
    parseReport(text).diagnostics.map((item) => item.rule),
    ["hooks.manager"],
  );
});
