import assert from "node:assert/strict";
import test from "node:test";

import { assetsFor } from "../src/assets.ts";
import { classes, policy } from "./ratchet-support.ts";

const command = ["node", "tools/plumb/bin/plumb.ts"];

const workflow = (extra: Record<string, unknown>): string =>
  assetsFor(policy(extra)).find((file) => file.path === ".github/workflows/plumb.yml")?.content ??
  "";

await test("the generated workflow runs the ratchet, pins its actions and stays read-only", () => {
  const text = workflow({ ci: { github: { command, setup: ["npm ci"] } }, commits: {} });
  assert.match(text, /^# generated by @quayro\/plumb;/);
  assert.match(text, /node tools\/plumb\/bin\/plumb\.ts check \$\{base:\+--base "\$base"\}\n/);
  assert.match(text, /fetch-depth: 0\n/);
  assert.match(text, /permissions:\n {2}contents: read\n/);
  assert.match(text, /- run: "npm ci"\n/);
  assert.match(text, /commits --message \\"\$PR_TITLE\\""\n/);
  // every action is a full commit, never a movable tag
  const uses = text.split("\n").filter((line) => line.includes("uses:"));
  assert.equal(uses.length, 2);
  assert.ok(uses.every((line) => /@[0-9a-f]{40} # v\d/.test(line)));
  // untrusted event text reaches the shell only through the environment
  assert.doesNotMatch(text, /run:.*\$\{\{/);
});

await test("the workflow follows the policy: runtime, branch and commit checks", () => {
  const bun = workflow({ ci: { github: { command: ["bun", "plumb.ts"], branch: "trunk" } } });
  assert.match(bun, /oven-sh\/setup-bun@[0-9a-f]{40}/);
  assert.match(bun, /branches: \["trunk"\]/);
  assert.match(bun, /"refs\/heads\/trunk"/);
  assert.doesNotMatch(bun, /commits --range/);
  assert.equal(workflow({}), "");
});

await test("a workflow cannot be bent through its policy values, and removing it is a weakening", () => {
  for (const github of [
    { command: ["node", "plumb.ts\nrm -rf /"] },
    { command, branch: "main' || true #" },
    { command, branch: "a b" },
    { command, setup: ["a\nb"] },
    { command: [] },
    {},
  ]) {
    assert.throws(() => policy({ ci: { github } }), TypeError, JSON.stringify(github));
  }
  // an argument with shell syntax stays one quoted word
  assert.match(
    workflow({ ci: { github: { command: ["node", "a b.ts", "$(id)"] } } }),
    /node 'a b\.ts' '\$\(id\)' check /,
  );
  const ci = { github: { command } };
  assert.deepEqual(classes({}, { ci }), ["tighten /ci"]);
  assert.deepEqual(classes({ ci }, {}), [
    "weaken /ci/github/command/0",
    "weaken /ci/github/command/1",
  ]);
});
