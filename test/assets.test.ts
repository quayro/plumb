import assert from "node:assert/strict";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import test from "node:test";

import { asset, assetsFor, checkAssets, syncAssets } from "../src/assets.ts";
import { policy } from "./support.ts";

function fixture(verify: (root: string) => void): void {
  const root = mkdtempSync(join(process.cwd(), ".plumb-asset-test-"));
  try {
    verify(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

await test("sync is idempotent and content drift fails", () => {
  fixture((root: string) => {
    const config = policy({ preset: "ozmikhail" });
    assert.equal(syncAssets({ root, config }).diagnostics.length, 0);
    assert.deepEqual(checkAssets({ root, config }), []);
    assert.deepEqual(syncAssets({ root, config }), { written: [], diagnostics: [] });
    writeFileSync(join(root, ".editorconfig"), "# generated by @ozmikhail/plumb; old\nwrong\n");
    assert.equal(checkAssets({ root, config })[0].rule, "generated.drift");
    assert.deepEqual(syncAssets({ root, config }).written, [".editorconfig"]);
    assert.deepEqual(checkAssets({ root, config }), []);
  });
});

await test("unchanged generated bytes do not conceal or preserve a missing executable mode", () => {
  fixture((root: string) => {
    const config = policy({
      preset: "portable",
      generated: [
        {
          path: "bin/run.sh",
          content: "#!/bin/sh\n# generated by @ozmikhail/plumb; do not edit\n",
          executable: true,
        },
      ],
    });
    syncAssets({ root, config });
    chmodSync(join(root, "bin/run.sh"), 0o644);
    assert.equal(checkAssets({ root, config })[0].rule, "generated.mode");
    assert.deepEqual(syncAssets({ root, config }).written, ["bin/run.sh"]);
    assert.equal(statSync(join(root, "bin/run.sh")).mode & 0o111, 0o111);
  });
});

await test("unrelated assets block the complete sync before any file changes", () => {
  fixture((root: string) => {
    const config = policy({ preset: "ozmikhail" });
    writeFileSync(join(root, ".editorconfig"), "root = true\n");
    const result = syncAssets({ root, config });
    assert.deepEqual(result.written, []);
    assert.equal(result.diagnostics[0].rule, "generated.ownership");
    assert.equal(readFileSync(join(root, ".editorconfig"), "utf8"), "root = true\n");
  });
});

await test("v0.4 generated assets upgrade without an adoption override", () => {
  fixture((root: string) => {
    writeFileSync(
      join(root, ".editorconfig"),
      "# generated by @ozmikhail/plumb; change plumb.config.ts, then run plumb sync\nold\n",
    );
    const config = policy({ preset: "ozmikhail" });
    assert.equal(syncAssets({ root, config }).diagnostics.length, 0);
    assert.deepEqual(checkAssets({ root, config }), []);
  });
});

await test("assets generated under the former @ozlabs scope are still owned and upgrade in place", () => {
  fixture((root: string) => {
    mkdirSync(join(root, ".githooks"), { recursive: true });
    writeFileSync(
      join(root, ".githooks/pre-commit"),
      "#!/bin/sh\n# generated by @ozlabs/plumb; edit plumb.json, then run plumb sync\nexec old check\n",
    );
    const config = policy({ preset: "portable", hooks: { command: ["plumb"] } });
    assert.deepEqual(syncAssets({ root, config }).diagnostics, []);
    assert.match(readFileSync(join(root, ".githooks/pre-commit"), "utf8"), /@quayro\/plumb;/);
    writeFileSync(
      join(root, ".githooks/pre-commit"),
      "#!/bin/sh\n# generated by @someone/plumb; edit plumb.json\n",
    );
    assert.equal(syncAssets({ root, config }).diagnostics[0].rule, "generated.ownership");
  });
});

await test("python and rust projects generate their tool policies in their own project roots", () => {
  const config = policy({
    preset: "portable",
    projects: [
      { root: "py", profile: "python" },
      { root: "crate", profile: "rust" },
    ],
  });
  const assets = assetsFor(config);
  assert.deepEqual(
    assets.map(({ path }) => path),
    ["crate/rustfmt.toml", "py/mypy.ini", "py/ruff.toml"],
  );
  for (const [path, name] of [
    ["py/ruff.toml", "ruff.toml"],
    ["py/mypy.ini", "mypy.ini"],
    ["crate/rustfmt.toml", "rustfmt.toml"],
  ] as const) {
    const content = assets.find((item) => item.path === path)?.content ?? "";
    assert.ok(content.endsWith(asset(name)), path);
    assert.match(content, /^# generated by/m, path);
  }
  fixture((root: string) => {
    syncAssets({ root, config });
    rmSync(join(root, "py/ruff.toml"));
    assert.deepEqual(
      checkAssets({ root, config }).map(({ rule, path }) => [rule, path]),
      [["generated.drift", "py/ruff.toml"]],
    );
  });
});

await test("custom generated data cannot replace preset-owned files", () => {
  assert.throws(
    () =>
      assetsFor(
        policy({ preset: "ozmikhail", generated: [{ path: ".editorconfig", content: "weaker" }] }),
      ),
    /cannot replace/,
  );
  assert.throws(
    () =>
      assetsFor(
        policy({
          preset: "ozmikhail",
          generated: [{ path: "./.editorconfig", content: "weaker" }],
        }),
      ),
    /cannot replace/,
  );
  assert.throws(
    () =>
      assetsFor(
        policy({
          preset: "portable",
          generated: [
            { path: "src/a.json", content: "{}" },
            { path: "src\\a.json", content: "[]" },
          ],
        }),
      ),
    /duplicate/,
  );
  fixture((root: string) => {
    const config = policy({
      preset: "portable",
      generated: [{ path: "config/settings.json", content: '{"version":1}\n' }],
    });
    assert.deepEqual(syncAssets({ root, config }).written, ["config/settings.json"]);
    assert.deepEqual(checkAssets({ root, config }), []);
    const updated = {
      ...config,
      generated: [{ path: "config/settings.json", content: '{"version":2}\n' }],
    };
    assert.deepEqual(syncAssets({ root, config: updated }).written, ["config/settings.json"]);
    assert.equal(readFileSync(join(root, "config/settings.json"), "utf8"), '{"version":2}\n');
  });
});

await test("conflicting generated file and directory paths fail before sync writes", () => {
  fixture((root: string) => {
    const config = policy({
      preset: "portable",
      generated: [
        { path: "output", content: "first" },
        { path: "output/data.json", content: "{}" },
      ],
    });
    assert.throws(() => syncAssets({ root, config }), /generated file cannot also be a directory/);
    assert.equal(existsSync(join(root, "output")), false);
    assert.throws(
      () =>
        assetsFor(
          policy({
            preset: "portable",
            projects: [{ root: "native", profile: "python" }],
            generated: [{ path: "native", content: "first" }],
          }),
        ),
      /generated file cannot also be a directory/,
    );
  });
});

await test("generated paths reject symlink parents and never touch their target", () => {
  fixture((root: string) => {
    mkdirSync(join(root, "real"));
    symlinkSync(join(root, "real"), join(root, "linked"), "dir");
    const config = policy({
      preset: "portable",
      generated: [{ path: "linked/out.txt", content: "new" }],
    });
    const result = syncAssets({ root, config });
    assert.deepEqual(result.written, []);
    assert.equal(result.diagnostics[0].status, "incomplete");
    assert.equal(existsSync(join(root, "real/out.txt")), false);
  });
});
